// ME Pro EQ — ME Audio
// Test runner. Usage: meproeq_dsp_tests [--filter substring] [--report path.md] [--list]
#include "TestFramework.h"

#include <chrono>
#include <cstring>
#include <filesystem>
#include <fstream>
#include <map>

#if defined(__SSE2__) || defined(_M_X64) || defined(_M_AMD64)
    #include <xmmintrin.h>
    #include <pmmintrin.h>
#endif

static void enableFlushToZero()
{
    // Matches what the plugin wrapper does on the audio thread (juce::ScopedNoDenormals).
#if defined(__SSE2__) || defined(_M_X64) || defined(_M_AMD64)
    _mm_setcsr (_mm_getcsr() | 0x8040); // FTZ | DAZ
#endif
}

int main (int argc, char** argv)
{
    std::string filter, reportPath;
    bool list = false;
    for (int i = 1; i < argc; ++i)
    {
        if (! std::strcmp (argv[i], "--filter") && i + 1 < argc)
            filter = argv[++i];
        else if (! std::strcmp (argv[i], "--report") && i + 1 < argc)
            reportPath = argv[++i];
        else if (! std::strcmp (argv[i], "--list"))
            list = true;
    }

    enableFlushToZero();

    auto& ctx = metest::Context::get();
    int run = 0, passed = 0, failed = 0;
    std::vector<std::pair<std::string, std::string>> results;
    std::vector<double> times;
    const auto t0 = std::chrono::steady_clock::now();

    for (auto& t : ctx.tests)
    {
        const std::string full = t.suite + "." + t.name;
        if (! filter.empty() && full.find (filter) == std::string::npos)
            continue;
        if (list)
        {
            std::printf ("%s\n", full.c_str());
            continue;
        }
        ctx.currentTest = full;
        ctx.currentFailed = false;
        std::printf ("[ RUN  ] %s\n", full.c_str());
        std::fflush (stdout);
        const auto a = std::chrono::steady_clock::now();
        try
        {
            t.fn();
        }
        catch (const std::exception& e)
        {
            metest::fail (std::string ("exception: ") + e.what(), __FILE__, __LINE__);
        }
        const double secs = std::chrono::duration<double> (std::chrono::steady_clock::now() - a).count();
        ++run;
        if (ctx.currentFailed)
            ++failed;
        else
            ++passed;
        results.push_back ({ full, ctx.currentFailed ? "FAIL" : "PASS" });
        times.push_back (secs);
        std::printf ("[ %s ] %s (%.2f s)\n", ctx.currentFailed ? "FAIL" : " OK ", full.c_str(), secs);
    }

    if (list)
        return 0;

    const double total = std::chrono::duration<double> (std::chrono::steady_clock::now() - t0).count();
    std::printf ("\n%d tests run, %d passed, %d failed (%d checks, %d failed checks) in %.1f s\n",
                 run, passed, failed, ctx.checks, ctx.failedChecks, total);

    if (! reportPath.empty())
    {
        std::filesystem::create_directories (std::filesystem::path (reportPath).parent_path());
        std::ofstream f (reportPath);
        f << "# ME Pro EQ — automated DSP test report\n\n";
        f << "Generated by `meproeq_dsp_tests`. Every number below was produced by the executed tests.\n\n";
        f << "**Summary:** " << run << " tests, " << passed << " PASS, " << failed << " FAIL; "
          << ctx.checks << " checks, " << ctx.failedChecks << " failed checks.\n\n";
        f << "| Test | Result | Time (s) |\n|---|---|---|\n";
        for (size_t i = 0; i < results.size(); ++i)
            f << "| " << results[i].first << " | " << results[i].second << " | " << metest::str (times[i]) << " |\n";
        f << "\n## Measurements\n";
        std::string last;
        for (auto& m : ctx.measurements)
        {
            if (m.test != last)
            {
                f << "\n### " << m.test << "\n\n| Quantity | Value |\n|---|---|\n";
                last = m.test;
            }
            f << "| " << m.key << " | " << m.value << " |\n";
        }
        if (! ctx.failures.empty())
        {
            f << "\n## Failures\n\n";
            for (auto& s : ctx.failures)
                f << "- " << s << "\n";
        }
        std::printf ("Report written to %s\n", reportPath.c_str());
    }
    return failed == 0 ? 0 : 1;
}
